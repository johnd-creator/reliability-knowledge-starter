import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const proxy=readFileSync('app/api/engineering-qa/[...path]/route.ts','utf8');
const page=readFileSync('app/engineering/qa/page.tsx','utf8');
const transport=readFileSync('lib/engineering-http.ts','utf8');
const ui=readFileSync('components/EngineeringQa.tsx','utf8');
const app=readFileSync('../src/api/app.py','utf8');
let count=0;const check=(label,value)=>{assert.ok(value,label);count++;console.log('PASS '+label);};
check('development gate',page.includes("NODE_ENV!=='development'")&&proxy.includes("NODE_ENV!=='development'"));
check('explicit separate QA opt-in',page.includes('NADI_ENGINEERING_QA_ENABLED')&&proxy.includes('NADI_ENGINEERING_QA_ENABLED'));
check('loopback bounded backend only',proxy.includes("['localhost','127.0.0.1']")&&proxy.includes('13\\d{3}'));
check('no redirects',proxy.includes("redirect:'error'"));
check('no actor/roles forwarded',!proxy.includes("'x-actor'")&&!proxy.includes("'authorization'"));
check('secure-session and CSRF transport',transport.includes("credentials:'same-origin'")&&transport.includes('X-CSRF-Token'));
check('no browser source credentials',!transport.includes('PI_PASSWORD')&&!transport.includes('MAXIMO_READ_ONLY_TOKEN'));
check('unsaved protection',ui.includes('beforeunload')&&ui.includes('Input retained'));
check('explicit unknown/nonoperational meaning',ui.includes('UNKNOWN')&&ui.includes('not operational plant evidence')&&ui.includes('NOT ASSESSED'));
check('production API never mounts QA',!app.includes('create_qa_app')&&!app.includes('build_session_router'));
console.log(`HTTP QA frontend checks passed: ${count}`);
